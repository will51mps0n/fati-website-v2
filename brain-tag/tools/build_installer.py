#!/usr/bin/env python3
"""Generate the Roblox Studio Command Bar installer.

Writes two files:
- studio/bundle.json: every Brain Tag script plus the project's service
  properties, as data.
- studio/install.luau: a small installer. The README's one-line command
  downloads it into a ModuleScript and calls the function it returns, which
  downloads bundle.json and (re)creates every script in the open place.

Studio caps a script's Source at 200,000 characters, so the scripts travel
as JSON (a plain string has no such cap) and each one is set separately.

Usage (from the brain-tag folder):
    python3 tools/build_installer.py path/to/rojo
"""

import datetime
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STUDIO = ROOT / "studio"
REPO = "will51mps0n/fati-website-v2"
BRANCH = "claude/pensive-mccarthy-jls1ep"
BUNDLE_PATH = "brain-tag/studio/bundle.json"
MAX_SOURCE = 200_000

# Containers every place already has. Anything below them that the project
# defines is replaced on each install.
CONTAINERS = {
    "ReplicatedStorage",
    "ServerScriptService",
    "StarterPlayer",
    "StarterPlayerScripts",
    "StarterCharacterScripts",
}
CREATED = {"Folder", "ModuleScript", "Script", "LocalScript"}
# String-valued properties in default.project.json that are really enums.
ENUM_PROPERTIES = {"ChatVersion"}


def property_value(name, value):
    """(kind, value) for the installer to turn into a Roblox value."""
    if isinstance(value, (bool, int, float)):
        return "plain", value
    if isinstance(value, list) and len(value) == 3:
        return "Color3", value
    if isinstance(value, str):
        return ("Enum", [name, value]) if name in ENUM_PROPERTIES else ("plain", value)
    raise SystemExit("build_installer: can't convert %s = %r" % (name, value))


def collect_properties(node, path, out):
    for name, value in node.get("$properties", {}).items():
        kind, converted = property_value(name, value)
        out.append({"path": path, "property": name, "kind": kind, "value": converted})
    for key, child in node.items():
        if not key.startswith("$") and isinstance(child, dict):
            collect_properties(child, path + [key], out)


def source_of(node):
    for file in node.get("filePaths", []):
        if file.endswith((".luau", ".lua")):
            source = (ROOT / file).read_text()
            if len(source.encode()) >= MAX_SOURCE:
                raise SystemExit("build_installer: %s is over Studio's script size limit" % file)
            return source
    return None


def collect_scripts(node, path, out, managed):
    for child in node.get("children", []):
        name, cls = child["name"], child["className"]
        if cls in CONTAINERS and not managed:
            collect_scripts(child, path + [name], out, False)
            continue
        if cls not in CREATED:
            raise SystemExit("build_installer: unexpected %s %s" % (cls, "/".join(path + [name])))
        entry = {"parent": "/".join(path), "name": name, "class": cls, "replaces": not managed}
        source = source_of(child)
        if source is not None:
            entry["source"] = source
        out.append(entry)
        collect_scripts(child, path + [name], out, True)


INSTALLER = """-- Brain Tag installer. Generated by tools/build_installer.py: do not edit.
-- The README's Command Bar line downloads this file into a ModuleScript and
-- calls the function it returns. That downloads bundle.json (every script,
-- as data) and (re)installs it into the place open in Roblox Studio.

local HttpService = game:GetService("HttpService")

local REPO = %(repo)s
local BRANCH = %(branch)s
local BUNDLE_PATH = %(bundle_path)s

-- GitHub's file server caches a branch's files for a few minutes after a
-- push, so ask the API for the branch's newest commit and download the
-- bundle from that exact commit (those URLs never go stale).
local function newestCommit(): string?
	local ok, sha = pcall(function()
		return HttpService:GetAsync(
			"https://api.github.com/repos/" .. REPO .. "/commits/" .. BRANCH,
			true,
			{ Accept = "application/vnd.github.sha" }
		)
	end)
	local clean = if ok and typeof(sha) == "string" then string.match(sha, "^%%s*(%%x+)%%s*$") else nil
	if clean and #clean == 40 then
		return clean
	end
	warn("[Brain Tag] couldn't ask GitHub for the newest version, using its cached copy: " .. tostring(sha))
	return nil
end

local function container(path)
	local names = string.split(path, "/")
	local instance = game:GetService(names[1])
	for i = 2, #names do
		local child = instance:FindFirstChild(names[i])
		if not child then
			child = Instance.new(names[i])
			child.Parent = instance
		end
		instance = child
	end
	return instance
end

local function convert(kind, value)
	if kind == "Color3" then
		return Color3.new(value[1], value[2], value[3])
	elseif kind == "Enum" then
		return Enum[value[1]][value[2]]
	end
	return value
end

return function()
	print("[Brain Tag] downloading...")
	local commit = newestCommit()
	local ref = commit or ("refs/heads/" .. BRANCH)
	local url = "https://raw.githubusercontent.com/" .. REPO .. "/" .. ref .. "/" .. BUNDLE_PATH
	local bundle = HttpService:JSONDecode(HttpService:GetAsync(url, true))

	local made = {}
	local count = 0
	for _, entry in bundle.scripts do
		local parent = made[entry.parent] or container(entry.parent)
		if entry.replaces then
			for _, old in parent:GetChildren() do
				if old.Name == entry.name then
					old:Destroy()
				end
			end
		end
		local instance = Instance.new(entry.class)
		instance.Name = entry.name
		if entry.source then
			instance.Source = entry.source
			count += 1
		end
		made[entry.parent .. "/" .. entry.name] = instance
		instance.Parent = parent
	end

	for _, setting in bundle.properties do
		local ok, err = pcall(function()
			local instance = game:GetService(setting.path[1])
			for i = 2, #setting.path do
				instance = instance:FindFirstChild(setting.path[i])
			end
			instance[setting.property] = convert(setting.kind, setting.value)
		end)
		if not ok then
			warn("[Brain Tag] couldn't set " .. setting.property .. ": " .. tostring(err))
		end
	end

	-- The Baseplate template's floor and spawn pad would sit on top of the map.
	local removed = {}
	for _, child in workspace:GetChildren() do
		if child:IsA("SpawnLocation") or (child.Name == "Baseplate" and child:IsA("BasePart")) then
			table.insert(removed, child.Name)
			child:Destroy()
		end
	end
	if #removed > 0 then
		print("[Brain Tag] removed from Workspace: " .. table.concat(removed, ", "))
	end

	pcall(function()
		game:GetService("ChangeHistoryService"):SetWaypoint("Install Brain Tag")
	end)
	print(
		("[Brain Tag] installed build %%s%%s (%%d scripts). Press Play to test."):format(
			bundle.build,
			if commit then ", commit " .. string.sub(commit, 1, 7) else "",
			count
		)
	)
end
"""


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    subprocess.run(
        [sys.argv[1], "sourcemap", "default.project.json", "-o", "sourcemap.json"],
        cwd=ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
    )
    sourcemap = json.loads((ROOT / "sourcemap.json").read_text())
    project = json.loads((ROOT / "default.project.json").read_text())

    scripts = []
    collect_scripts(sourcemap, [], scripts, False)
    properties = []
    collect_properties(project["tree"], [], properties)
    build = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    STUDIO.mkdir(exist_ok=True)
    bundle = STUDIO / "bundle.json"
    bundle.write_text(
        json.dumps({"build": build, "scripts": scripts, "properties": properties}, ensure_ascii=False, indent=1)
    )
    installer = STUDIO / "install.luau"
    installer.write_text(
        INSTALLER
        % {"repo": json.dumps(REPO), "branch": json.dumps(BRANCH), "bundle_path": json.dumps(BUNDLE_PATH)}
    )
    print(
        "wrote %s (%d scripts, %d KB) and %s (%d bytes)"
        % (
            bundle.relative_to(ROOT),
            len(scripts),
            bundle.stat().st_size // 1024,
            installer.relative_to(ROOT),
            installer.stat().st_size,
        )
    )


if __name__ == "__main__":
    main()

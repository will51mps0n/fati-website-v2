#!/usr/bin/env python3
"""Generate studio/install.luau, the Roblox Studio Command Bar installer.

The README's one-line command downloads that file into a ModuleScript and
calls the function it returns. The function (re)creates every Brain Tag
script in the place that is open in Studio and applies the project's
service properties, so the game can be installed and updated without
leaving Studio.

Usage (from the brain-tag folder):
    python3 tools/build_installer.py path/to/rojo
"""

import datetime
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "studio" / "install.luau"

# Containers every place already has. Anything below them that the project
# defines is replaced on each install.
CONTAINERS = {
    "ReplicatedStorage",
    "ServerScriptService",
    "StarterPlayer",
    "StarterPlayerScripts",
    "StarterCharacterScripts",
}
CREATED = {"Folder", "ModuleScript", "Script", "LocalScript"}
# String-valued properties in default.project.json that are really enums.
ENUM_PROPERTIES = {"ChatVersion"}


def lua_string(text: str) -> str:
    """A Luau long-bracket string holding `text` exactly."""
    level = 0
    while True:
        close = "]" + "=" * level + "]"
        # The first closing bracket must be the one we append.
        if (text + close).find(close) == len(text):
            # A newline right after the opening bracket is dropped by Luau.
            return "[" + "=" * level + "[\n" + text + close
        level += 1


def lua_value(name: str, value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list) and len(value) == 3:
        return "Color3.new(%s, %s, %s)" % tuple(repr(v) for v in value)
    if isinstance(value, str):
        if name in ENUM_PROPERTIES:
            return "Enum.%s.%s" % (name, value)
        return json.dumps(value)
    raise SystemExit("build_installer: can't convert %s = %r" % (name, value))


def collect_properties(node, path, out):
    for name, value in node.get("$properties", {}).items():
        out.append((path, name, lua_value(name, value)))
    for key, child in node.items():
        if not key.startswith("$") and isinstance(child, dict):
            collect_properties(child, path + [key], out)


def source_of(node) -> str | None:
    for file in node.get("filePaths", []):
        if file.endswith((".luau", ".lua")):
            return (ROOT / file).read_text()
    return None


def collect_scripts(node, path, out, managed):
    for child in node.get("children", []):
        name, cls = child["name"], child["className"]
        if cls in CONTAINERS and not managed:
            collect_scripts(child, path + [name], out, False)
            continue
        if cls not in CREATED:
            raise SystemExit("build_installer: unexpected %s %s" % (cls, "/".join(path + [name])))
        out.append(("/".join(path), name, cls, source_of(child), not managed))
        collect_scripts(child, path + [name], out, True)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    rojo = sys.argv[1]
    subprocess.run(
        [rojo, "sourcemap", "default.project.json", "-o", "sourcemap.json"],
        cwd=ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
    )
    sourcemap = json.loads((ROOT / "sourcemap.json").read_text())
    project = json.loads((ROOT / "default.project.json").read_text())

    scripts = []
    collect_scripts(sourcemap, [], scripts, False)
    properties = []
    collect_properties(project["tree"], [], properties)

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "-- Brain Tag installer. Generated by tools/build_installer.py: do not edit.",
        "-- The README's Command Bar line downloads this file into a ModuleScript and",
        "-- calls the function it returns, which (re)installs every Brain Tag script",
        "-- into the place open in Roblox Studio.",
        "",
        "local BUILD = %s" % json.dumps(stamp),
        "",
        "-- { parent path, name, class, source, replaces an existing child }",
        "local SCRIPTS = {",
    ]
    for parent, name, cls, source, top in scripts:
        src = lua_string(source) if source is not None else "nil"
        lines.append(
            "\t{ %s, %s, %s, %s, %s },"
            % (json.dumps(parent), json.dumps(name), json.dumps(cls), src, "true" if top else "false")
        )
    lines.append("}")
    lines.append("")
    lines.append("local function applyProperties()")
    lines.append("\tlocal function set(path, property, value)")
    lines.append("\t\tlocal ok, err = pcall(function()")
    lines.append("\t\t\tlocal instance = game:GetService(path[1])")
    lines.append("\t\t\tfor i = 2, #path do")
    lines.append("\t\t\t\tinstance = instance:FindFirstChild(path[i])")
    lines.append("\t\t\tend")
    lines.append("\t\t\tinstance[property] = value")
    lines.append("\t\tend)")
    lines.append("\t\tif not ok then")
    lines.append('\t\t\twarn("[Brain Tag] couldn\'t set " .. property .. ": " .. tostring(err))')
    lines.append("\t\tend")
    lines.append("\tend")
    for path, name, value in properties:
        lines.append("\tset({ %s }, %s, %s)" % (", ".join(json.dumps(p) for p in path), json.dumps(name), value))
    lines.append("end")
    lines.append(TEMPLATE)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print("wrote %s (%d scripts, %d KB)" % (OUT.relative_to(ROOT), len(scripts), OUT.stat().st_size // 1024))


TEMPLATE = """
local function container(path)
	local names = string.split(path, "/")
	local instance = game:GetService(names[1])
	for i = 2, #names do
		local child = instance:FindFirstChild(names[i])
		if not child then
			child = Instance.new(names[i])
			child.Parent = instance
		end
		instance = child
	end
	return instance
end

return function()
	local made = {}
	local count = 0
	for _, entry in SCRIPTS do
		local parentPath, name, className, source, replaces = entry[1], entry[2], entry[3], entry[4], entry[5]
		local parent = made[parentPath] or container(parentPath)
		if replaces then
			for _, old in parent:GetChildren() do
				if old.Name == name then
					old:Destroy()
				end
			end
		end
		local instance = Instance.new(className)
		instance.Name = name
		if source then
			instance.Source = source
			count += 1
		end
		made[parentPath .. "/" .. name] = instance
		instance.Parent = parent
	end
	applyProperties()

	-- The Baseplate template's floor and spawn pad would sit on top of the map.
	local removed = {}
	for _, child in workspace:GetChildren() do
		if child:IsA("SpawnLocation") or (child.Name == "Baseplate" and child:IsA("BasePart")) then
			table.insert(removed, child.Name)
			child:Destroy()
		end
	end
	if #removed > 0 then
		print("[Brain Tag] removed from Workspace: " .. table.concat(removed, ", "))
	end

	pcall(function()
		game:GetService("ChangeHistoryService"):SetWaypoint("Install Brain Tag")
	end)
	print(("[Brain Tag] installed build %s (%d scripts). Press Play to test."):format(BUILD, count))
end
"""

if __name__ == "__main__":
    main()
